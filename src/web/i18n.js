// BCP-47 태그 → 지원 언어 코드 (미지원이면 영어)
function resolveLang(tag) {
  const t = (tag || '').toLowerCase();
  if (t.startsWith('zh')) {
    return (t.includes('tw') || t.includes('hant') || t.includes('hk') || t.includes('mo')) ? 'zh-TW' : 'zh-CN';
  }
  if (t.startsWith('pt')) return 'pt-BR';
  const two = t.slice(0, 2);
  for (const code of Object.keys(I18N)) if (code.slice(0, 2) === two) return code;
  return 'en';
}
